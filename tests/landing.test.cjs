require('./helpers/register-ts.cjs')
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const React = require('react')
const { renderToStaticMarkup } = require('react-dom/server')
require.extensions['.css'] = module => { module.exports = { __esModule: true, default: new Proxy({}, { get: (_, name) => name }) } }
const render = (name) => renderToStaticMarkup(React.createElement(require(`../src/components/landing/${name}.tsx`)[name]))
test('landing communicates the product without waiting for animated text', () => {
  const html = render('Hero')
  assert.match(html, /Tu dinero\./)
  assert.match(html, /bajo control/)
  assert.match(html, /data-hero-layout="burst"/)
  assert.match(html, /class="heroEmblem"/)
  assert.doesNotMatch(html, /phoneIsland|class="workspace"/)
  assert.match(html, /href="\/auth\/register"/)
  assert.match(html, /Vista de ejemplo/)
  assert.doesNotMatch(html, /Datos 100% seguros|animate-float|bg-gradient/)
})
test('landing retains section anchors and registration at the close', () => {
  assert.match(render('Features'), /id="features"/)
  assert.match(render('HowItWorks'), /id="how-it-works"/)
  assert.match(render('CTA'), /href="\/auth\/register"/)
})
test('landing demonstrates expenses in layered product scenes instead of icon-only tiles', () => {
  const html = render('Features')
  assert.match(html, /data-scene="budget"/)
  assert.match(html, /data-scene="recurring"/)
  assert.match(html, /data-scene="categories"/)
  assert.match(html, /datos ilustrativos/)
})
test('hero is scroll-driven, illustrative and labelled as sample data', () => {
  const html = render('Hero')
  assert.match(html, /class="heroTrack"/)
  assert.equal((html.match(/class="heroChip"/g) || []).length, 6)
  assert.match(html, /role="img" aria-label="Ilustración de ejemplo/)
  assert.match(html, /datos ilustrativos/)
  const source = fs.readFileSync(path.join(__dirname, '../src/components/landing/Hero.tsx'), 'utf8')
  assert.match(source, /addEventListener\('scroll'/)
  assert.match(source, /reduced/)
  const css = fs.readFileSync(path.join(__dirname, '../src/components/landing/landing.module.css'), 'utf8')
  assert.match(css, /position: sticky/)
  assert.match(css, /\.heroStage\[data-static="true"\]/)
})

test('marketing motion has a pause control and reduced-motion policy', () => {
  const { LandingMotion, MotionToggle } = require('../src/components/landing/LandingMotion.tsx')
  const html = renderToStaticMarkup(React.createElement(LandingMotion, null, React.createElement(MotionToggle)))
  assert.match(html, /data-motion-paused="false"/)
  assert.match(html, /aria-label="Pausar animaciones"/)
  assert.match(html, /aria-pressed="false"/)
  const css = fs.readFileSync(path.join(__dirname, '../src/components/landing/landing.module.css'), 'utf8')
  assert.match(css, /prefers-reduced-motion:reduce/)
  assert.match(css, /animation-play-state: paused !important/)
  assert.doesNotMatch(css, /transition:\s*all|@keyframes[^}]*\b(?:width|height|left|top):/)
})

test('landing uses the app palette without metallic or pastel surface treatments', () => {
  const css = fs.readFileSync(path.join(__dirname, '../src/components/landing/landing.module.css'), 'utf8')
  for (const token of ['background', 'foreground', 'primary', 'card', 'border']) {
    assert.ok(css.includes(`hsl(var(--${token}))`), `Missing app token: ${token}`)
  }
  assert.doesNotMatch(css, /(?:linear|radial)-gradient\(|,\s*inset\b|#[0-9a-f]{3,8}\b/i)
})

test('mobile navigation exposes its expanded state and controlled menu', () => {
  const source = fs.readFileSync(path.join(__dirname, '../src/components/landing/Navbar.tsx'), 'utf8')
  assert.match(source, /aria-expanded=/)
  assert.match(source, /aria-controls=/)
  assert.match(source, /aria-label=/)
})
