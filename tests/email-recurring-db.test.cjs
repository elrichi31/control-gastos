const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { PGlite } = require('@electric-sql/pglite')
const owner = '11111111-1111-4111-8111-111111111111'
async function setup() {
  const db = new PGlite()
  await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
    CREATE TABLE gasto_recurrente(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id text NOT NULL,descripcion text NOT NULL,monto numeric NOT NULL,categoria_id integer NOT NULL,metodo_pago_id integer NOT NULL,frecuencia text NOT NULL,dia_mes bigint,dia_semana bigint,fecha_inicio date NOT NULL,fecha_fin date,activo boolean NOT NULL DEFAULT true);
    CREATE TABLE gasto(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id uuid NOT NULL,descripcion text NOT NULL,monto numeric NOT NULL,categoria_id integer NOT NULL,metodo_pago_id integer NOT NULL,fecha date NOT NULL,is_recurrent boolean NOT NULL DEFAULT false,tags text[]);
    CREATE TABLE gasto_recurrente_instancia(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,gasto_recurrente_id bigint REFERENCES gasto_recurrente(id),gasto_id bigint REFERENCES gasto(id),fecha_programada date NOT NULL,estado text NOT NULL,generado_en timestamptz);`)
  for (const file of ['20261003_recurring_single_cron.sql', '20261005_recurring_calendar_tz.sql', '20261006_recurring_skip_prices.sql', '20261014_recurring_user_id_cast.sql', '20261015_foreign_tax.sql', '20261010_correo_consumo.sql', '20261011_correo_consumo_vinculos.sql']) await db.exec(fs.readFileSync(path.join(__dirname, '../supabase/migrations', file), 'utf8'))
  await db.exec(`INSERT INTO gasto_recurrente(user_id,descripcion,monto,categoria_id,metodo_pago_id,frecuencia,dia_mes,fecha_inicio) VALUES('${owner}','Netflix',10,1,2,'mensual',15,'2026-10-01');
    INSERT INTO correo_consumo(user_id,email_message_id,origen,fecha,descripcion,monto,tipo) VALUES('${owner}','mail-1','Banco','2026-10-16','NETFLIX.COM',12,'gasto'),('${owner}','mail-2','Banco','2026-10-16','NETFLIX.COM',12,'gasto');`)
  return db
}
const migration = () => fs.readFileSync(path.join(__dirname, '../supabase/migrations/20261016_email_recurring.sql'), 'utf8')
const confirm = (db, update = false, who = owner, expected = 10, tax = null, mail = 1) => db.query('SELECT confirm_email_recurring($1,$2,$3,$4::date,$5,$6,$7::jsonb) AS result', [who, mail, 1, '2026-10-15', update, expected, tax === null ? null : JSON.stringify(tax)])
test('PostgreSQL: confirmar antes del cron crea una sola ocurrencia y el precio futuro requiere opt-in', async () => {
  const db = await setup(); try {
    await db.exec(migration())
    assert.equal((await confirm(db, true)).rows[0].result.monto, 12)
    assert.equal((await db.query("SELECT process_recurring_expenses('2026-10-15'::date,200) AS r")).rows[0].r.created, 0)
    assert.equal((await db.query("SELECT process_recurring_expenses('2026-11-15'::date,200) AS r")).rows[0].r.created, 1)
    assert.deepEqual((await db.query('SELECT monto::float8 AS monto,fecha::text AS fecha FROM gasto ORDER BY fecha')).rows, [{ monto: 12, fecha: '2026-10-15' }, { monto: 12, fecha: '2026-11-15' }])
    assert.equal((await db.query('SELECT monto_esperado::float8 AS expected FROM correo_consumo WHERE id=1')).rows[0].expected, 10)
  } finally { await db.close() }
})
test('PostgreSQL: conserva ISD, IVA y porcentaje personalizado redondeando cada línea como la app', async () => {
  const db = await setup(); try {
    await db.exec(migration())
    const tax = { base: 10, selected: ['isd', 'iva_digital', 'custom'], customRate: '2,5' }
    await db.query('UPDATE gasto_recurrente SET monto=12.25,impuesto_exterior=$1::jsonb', [JSON.stringify(tax)])
    await db.exec('UPDATE correo_consumo SET monto=15.99 WHERE id=1')
    const result = (await confirm(db, true, owner, 12.25, tax)).rows[0].result
    assert.equal(result.monto, 19.59)
    const expense = (await db.query('SELECT monto::float8 AS monto,impuesto_exterior,tags FROM gasto')).rows[0]
    assert.deepEqual(expense, { monto: 19.59, impuesto_exterior: { ...tax, base: 15.99 }, tags: ['exterior'] })
    assert.equal((await db.query('SELECT monto::float8 AS monto FROM gasto_recurrente')).rows[0].monto, 19.59)
  } finally { await db.close() }
})
test('PostgreSQL: fallo al vincular revierte gasto, precio y correo juntos', async () => {
  const db = await setup(); try {
    await db.exec(migration())
    await db.exec("ALTER TABLE correo_consumo ADD CONSTRAINT fail_confirmation CHECK(estado <> 'vinculado')")
    await assert.rejects(() => confirm(db, true), /fail_confirmation/)
    assert.equal((await db.query('SELECT count(*)::int AS n FROM gasto')).rows[0].n, 0)
    assert.equal((await db.query('SELECT monto::float8 AS monto FROM gasto_recurrente')).rows[0].monto, 10)
    assert.equal((await db.query('SELECT estado FROM correo_consumo WHERE id=1')).rows[0].estado, 'pendiente')
    await db.exec('ALTER TABLE correo_consumo DROP CONSTRAINT fail_confirmation')
    assert.equal((await confirm(db, true)).rows[0].result.vinculados, 1)
  } finally { await db.close() }
})
test('PostgreSQL: roles públicos, otro dueño y precio obsoleto no pueden confirmar', async () => {
  const db = await setup(); try {
    await db.exec(migration())
    for (const role of ['anon', 'authenticated']) {
      await db.exec(`SET ROLE ${role}`)
      await assert.rejects(() => confirm(db), /permission denied/)
      await db.exec('RESET ROLE')
    }
    await assert.rejects(() => confirm(db, false, '22222222-2222-4222-8222-222222222222'), /no encontrado/)
    await assert.rejects(() => confirm(db, true, owner, 9), /precio cambió/)
    await db.exec("UPDATE correo_consumo SET user_id='otro' WHERE id=1")
    await assert.rejects(() => confirm(db), /Correo no encontrado/)
    assert.equal((await db.query('SELECT count(*)::int AS n FROM gasto')).rows[0].n, 0)
  } finally { await db.close() }
})
test('PostgreSQL: no recrea fechas consumidas eliminadas ni una regla pausada sin gasto', async () => {
  const db = await setup(); try {
    await db.exec(migration())
    await db.exec('UPDATE gasto_recurrente SET activo=false')
    await assert.rejects(() => confirm(db), /omitido o eliminado/)
    await db.exec("UPDATE gasto_recurrente SET activo=true,proxima_fecha='2026-10-15'")
    await db.exec("SELECT process_recurring_expenses('2026-10-15'::date,200); DELETE FROM gasto")
    await assert.rejects(() => confirm(db), /omitido o eliminado/)
    assert.equal((await db.query('SELECT estado FROM correo_consumo WHERE id=1')).rows[0].estado, 'pendiente')
  } finally { await db.close() }
})

test('PostgreSQL: confirmar reutiliza el gasto generado y cambia solo este cobro; reintentos no duplican', async () => {
  const db = await setup(); try {
    await db.exec(migration())
    await db.exec("SELECT process_recurring_expenses('2026-10-15'::date,200)")
    const result = (await confirm(db)).rows[0].result
    assert.equal(result.vinculados, 1)
    assert.deepEqual((await db.query('SELECT monto::float8 AS monto,fecha::text AS fecha FROM gasto')).rows, [{ monto: 12, fecha: '2026-10-15' }])
    assert.equal((await db.query('SELECT monto::float8 AS monto FROM gasto_recurrente')).rows[0].monto, 10)
    assert.equal((await confirm(db)).rows[0].result.vinculados, 0)
    await assert.rejects(() => confirm(db, false, owner, 10, null, 2), /confirmado/)
    assert.equal((await db.query('SELECT count(*)::int AS n FROM gasto')).rows[0].n, 1)
    await db.exec(migration())
  } finally { await db.close() }
})
